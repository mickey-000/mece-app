# --------------------------------------------------
# 2. アプリ設定 & セッション管理
# --------------------------------------------------
st.set_page_config(page_title="MECE Master 30", page_icon="🧩")

if 'game_state' not in st.session_state:
    st.session_state.game_state = "START" # START, QUIZ, RESULT
if 'questions' not in st.session_state:
    st.session_state.questions = []
if 'current_idx' not in st.session_state:
    st.session_state.current_idx = 0
if 'score' not in st.session_state:
    st.session_state.score = 0
if 'answered' not in st.session_state:
    st.session_state.answered = False
if 'last_result' not in st.session_state:
    st.session_state.last_result = None

# --------------------------------------------------
# 3. 画面描画
# --------------------------------------------------

# --- スタート画面 ---
if st.session_state.game_state == "START":
    st.title("🧩 MECEマスター 30")
    st.write("「漏れなく、ダブりなく」の思考を鍛える30問の特訓。")
    st.write("毎回ランダムに5問が出題されます。全正解を目指しましょう！")
    
    if st.button("特訓を開始する", use_container_width=True):
        st.session_state.questions = random.sample(all_scenarios, 5)
        st.session_state.current_idx = 0
        st.session_state.score = 0
        st.session_state.game_state = "QUIZ"
        st.session_state.answered = False
        st.rerun()

# --- クイズ画面 ---
elif st.session_state.game_state == "QUIZ":
    q = st.session_state.questions[st.session_state.current_idx]
    
    st.markdown(f"### 第 {st.session_state.current_idx + 1} 問 / 全 5 問")
    st.progress((st.session_state.current_idx) / 5)
    
    st.sidebar.subheader(f"難易度: {q['level']}")
    st.sidebar.write(f"テーマ: {q['title']}")
    
    st.info(f"**【お題】** {q['q']}")
    
    # 選択肢ボタン
    # 回答前
    if not st.session_state.answered:
        for opt in q['opts']:
            if st.button(opt, use_container_width=True):
                st.session_state.answered = True
                if opt == q['cor']:
                    st.session_state.score += 1
                    st.session_state.last_result = "CORRECT"
                else:
                    st.session_state.last_result = "WRONG"
                st.rerun()
    # 回答後
    else:
        if st.session_state.last_result == "CORRECT":
            st.success("✨ 正解！")
        else:
            st.error(f"❌ 不正解... 正解は「{q['cor']}」でした。")
        
        st.markdown(f"**解説:** {q['exp']}")
        
        if st.button("次へ進む ➔", use_container_width=True):
            st.session_state.current_idx += 1
            st.session_state.answered = False
            if st.session_state.current_idx >= 5:
                st.session_state.game_state = "RESULT"
            st.rerun()

# --- 結果画面 ---
elif st.session_state.game_state == "RESULT":
    st.title("🏁 特訓終了！")
    score = st.session_state.score
    st.header(f"今回のスコア: {score} / 5 点")
    
    # 称号システム
    if score == 5:
        rank = "👑 MECEマスター（もはやコンサル級）"
    elif score >= 4:
        rank = "🔥 ロジカル・リーダー（部下から信頼されるレベル）"
    elif score >= 3:
        rank = "🏃 期待の若手（さらなる高みを目指そう）"
    else:
        rank = "🌱 伸びしろ捜査官（まずは日常の整理から！）"
        
    st.subheader(f"あなたの称号: {rank}")
    
    if st.button("もう一度特訓する", use_container_width=True):
        st.session_state.game_state = "START"
        st.rerun()